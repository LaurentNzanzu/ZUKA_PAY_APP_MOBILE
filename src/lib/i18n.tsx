export type ExtraKey = keyof (typeof extra)["fr"];

export type TKey = keyof (typeof dict)["fr"] | ExtraKey;

export const LOCALES: Record<Lang, string> = { fr: "fr-FR", en: "en-GB", sw: "sw-KE" };

export type Tri = { fr: string; en: string; sw: string };

/** Picks the text for a language — for texts that live next to their component. */
export function pick(lang: Lang, m: Tri): string {
  return m[lang] ?? m.fr;
}

/** Dictionary language used to render a UI language (others are translated live from English). */
export function baseLang(ui: string): Lang {
  return ui === "fr" || ui === "en" || ui === "sw" ? ui : "en";
}

/** Chosen interface language code (any supported language). */
export function currentUiLang(): string {
  if (typeof window === "undefined") return "fr";
  const s = localStorage.getItem("zuki.lang");
  return findLanguage(s)?.code ?? "fr";
}

/** Current dictionary language outside React (PDF, store errors). */
export function currentLang(): Lang {
  return baseLang(currentUiLang());
}

interface I18nValue {
  /** Dictionary language (fr/en/sw). */
  lang: Lang;
  /** Language chosen by the user (any of WORLD_LANGUAGES). */
  uiLang: string;
  setLang: (code: string) => void;
  t: (key: TKey) => string;
  L: (m: Tri) => string;
  formatDate: (iso: string, opts?: Intl.DateTimeFormatOptions) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

function applyDocument(code: string) {
  document.documentElement.lang = code;
  document.documentElement.dir = findLanguage(code)?.rtl ? "rtl" : "ltr";
}

function safeLocale(code: string) {
  try {
    return Intl.DateTimeFormat.supportedLocalesOf([code]).length ? code : LOCALES[baseLang(code)];
  } catch {
    return LOCALES[baseLang(code)];
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [uiLang, setUiLang] = useState<string>("fr");

  useEffect(() => {
    const stored = findLanguage(localStorage.getItem("zuki.lang"))?.code;
    const initial = stored ?? matchDeviceLanguage(navigator.language || "fr");
    setUiLang(initial);
    localStorage.setItem("zuki.lang", initial);
    applyDocument(initial);
  }, []);

  const setLang = useCallback((code: string) => {
    const c = findLanguage(code)?.code ?? "fr";
    setUiLang(c);
    localStorage.setItem("zuki.lang", c);
    applyDocument(c);
  }, []);

  const lang = baseLang(uiLang);

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      uiLang,
      setLang,
      L: (m) => pick(lang, m),
      t: (key) => {
        const base = dict[lang] as Record<string, string>;
        const ext = extra[lang] as Record<string, string>;
        return (
          base[key] ??
          ext[key] ??
          (dict.fr as Record<string, string>)[key] ??
          (extra.fr as Record<string, string>)[key] ??
          key
        );
      },
      formatDate: (iso, opts = { day: "2-digit", month: "short", year: "numeric" }) =>
        new Intl.DateTimeFormat(safeLocale(uiLang), opts).format(new Date(`${iso}T12:00:00`)),
    }),
    [lang, uiLang, setLang],
  );

  return (
    <I18nContext.Provider value={value}>
      {children}
      {!BUILTIN.has(uiLang) && <DomTranslator lang={uiLang} />}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
